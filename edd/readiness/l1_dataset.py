def _case(
    name: str,
    tags: list[str],
    query: str,
    *,
    destinations: list[set[str]],
    intents: set[str],
    required_topics: list[set[str]] | None = None,
    allowed_topics: set[str] | None = None,
    min_searches: int = 1,
    max_searches: int = 3,
    min_unique_topics: int = 1,
    required_query_terms: list[set[str]] | None = None,
    official_domains: dict[str, set[str]] | None = None,
    clarification: bool = False,
) -> dict:
    return {
        "name": name,
        "tags": tags,
        "query": query,
        "expected": {
            "destinations": destinations,
            "intents": intents,
            "required_topics": required_topics or [],
            "allowed_topics": allowed_topics or set(),
            "min_searches": min_searches,
            "max_searches": max_searches,
            "min_unique_topics": min_unique_topics,
            "required_query_terms": required_query_terms or [],
            "official_domains": official_domains or {},
            "clarification": clarification,
        },
    }


